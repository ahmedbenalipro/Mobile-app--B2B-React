export function makeScripts(campaign, region) {
  const copy = REGIONAL_COPY[region] || REGIONAL_COPY.France;
  const isSurvey = campaign === 'b2c';
  return [
    {
      id: 'opener',
      stage: 'OPENER',
      prompt: `${copy.greeting} ${isSurvey ? copy.survey : copy.offer}`,
      responses: [
        { label: copy.yes, next: 'discovery' },
        { label: copy.competitor, next: 'competitor' },
        { label: copy.email, next: 'email' },
        { label: copy.gatekeeper, next: 'gatekeeper' },
      ],
    },
    {
      id: 'discovery',
      stage: 'DISCOVERY',
      prompt: isSurvey ? copy.surveyDiscovery : copy.discovery,
      responses: [
        { label: copy.interested, next: 'closing' },
        { label: copy.followup, next: 'closing' },
        { label: copy.budgetResponse, next: 'budget' },
      ],
    },
    {
      id: 'competitor',
      stage: 'DISCOVERY',
      prompt: isSurvey
        ? `${copy.surveyCompare} ${region === 'English' ? 'What stood out to you most?' : 'Qu’est-ce qui vous a le plus marqué ?'}`
        : `${copy.competitor} ${region === 'English' ? 'What matters most in your current approach?' : 'Qu’est-ce qui compte le plus dans votre approche actuelle ?'}`,
      responses: [
        { label: copy.simple, next: 'closing' },
        { label: copy.compare, next: 'closing' },
        { label: copy.satisfied, next: 'email' },
      ],
    },
    {
      id: 'email',
      stage: 'DISCOVERY',
      prompt: isSurvey
        ? copy.surveyPermission
        : `${copy.email} ${region === 'English' ? 'What would be most useful to see?' : 'Qu’aimeriez-vous voir en priorité ?'}`,
      responses: [
        { label: copy.overview, next: 'closing' },
        { label: copy.pricing, next: 'budget' },
        { label: copy.stop, next: null },
      ],
    },
    {
      id: 'gatekeeper',
      stage: 'DISCOVERY',
      prompt: `${copy.gatekeeper} ${region === 'English' ? 'Who would be the best person for me to speak with?' : 'À qui me conseilleriez-vous de m’adresser ?'}`,
      responses: [
        { label: copy.name, next: 'closing' },
        { label: copy.generalEmail, next: 'email' },
      ],
    },
    {
      id: 'budget',
      stage: 'DISCOVERY',
      prompt: isSurvey
        ? `${copy.surveyDiscovery} ${region === 'English' ? 'How often do you use this kind of service?' : 'À quelle fréquence utilisez-vous ce type de service ?'}`
        : `${copy.budget} ${region === 'English' ? 'If it becomes a priority, when would be a better time to revisit it?' : 'Si le sujet devient prioritaire, quel serait le meilleur moment pour en reparler ?'}`,
      responses: [
        { label: copy.nextQuarter, next: 'closing' },
        { label: copy.noCalendar, next: null },
        { label: copy.overview, next: 'email' },
      ],
    },
    {
      id: 'closing',
      stage: 'CLOSING',
      prompt: isSurvey ? copy.surveyClose : copy.close,
      responses: [
        { label: copy.meeting, next: null },
        { label: copy.callback, next: null },
        { label: copy.decline, next: null },
      ],
    },
  ];
}

